"""改图.py —— 「拿图去改图」的唯一入口。

为什么要有它：
2026-09-30 翻车 —— 拿着一张底稿就去换整片版图，新地图明明攥在手里却没挂上去，
出来整张废掉。复盘时发现：skill 里写了两处、项目自己的 生图提示词/修正帧_..._v6.txt
里也有一份完全正确的四件套提示词。**「写下来」挡不住「没读」。**
所以这里把规矩做成关卡：不是提醒你挂图，是**不挂图就跑不起来**。

两道关卡（对应 SKILL.md §9.5 关卡 A / 关卡 B）：
  关卡 A（清单）：每个画面元素都必须声明「本版」。漏一个元素 = 没想清楚 = 拦下。
  关卡 B（定稿图）：声明「本版=换」的元素，必须给出定稿图路径且文件真存在。
                   给不出 = 你要换一样东西却没给那样东西 = 拦下。
                    —— 2026-09-30 就是死在这一条上（要换地图，却没挂新地图）。

🔴 项目形态（2026-10-07 新增）：
  清单顶层可写 `"项目类型": "改图"`（默认）或 `"项目类型": "新建"`。
  「改图」= 帧是从既有成片里扫出来的 → 关卡 H 要求 `取帧命令` 里有 `--起/--止`。
  「新建」= 锚定帧是凭空做出来的，**没有成片可扫** → 关卡 H 跳过起止比对，
            改问「这张锚定帧从哪来」（`取帧.锚定帧来源`）；关卡 G 也允许「帧问题清单」为空。
  不写这个字段 = 按「改图」办（向后兼容）。
  —— 2026-10-07 之前没有这个开关，新建项目在关卡 H/G 三处永久卡死，
    逼着人绕开这道唯一入口。见 1007/MG技能介绍MG/1007/技能体检_实测发现.md。

用法：
    python3 改图.py --清单 0930/案例MG/镜头清单.json --镜头 02 \\
            --要改 "把整片版图整块删掉，照定稿版图重画一片新的"
    # 默认只打印不提交（dry-run）；看清楚了再加 --go 真跑

退出码：0 = 通过；1 = 校验不通过（**不花积分**）
"""
