def 读清单(路径):
    if not os.path.exists(路径):
        return None, "清单不存在：%s" % 路径
    try:
        with open(路径, encoding="utf-8") as fh:
            return json.load(fh), None
    except Exception as exc:
        return None, "清单不是合法 JSON：%s" % exc


def 是新建项目(清单):
    """这个项目的帧是「扫出来的」还是「凭空做出来的」？

    新建项目（如「MG 技能介绍片」）没有成片可扫，锚定帧是从零做出来的，
    关卡 H 的 `--起/--止` 比对和关卡 G 的「病在哪几条」都无从谈起。
    由清单顶层 `"项目类型"` 显式声明；不写 = 按「改图」办（向后兼容）。
    """
    return str(清单.get("项目类型") or "").strip() == "新建"


def 找更新的候选(根, 底稿相对路径, 镜头号):
    """扫出比底稿更新、且像是"本镜候选"的图片 —— 防止拿一张过期的底稿一路改下去。

    只认两类命中，免得把项目里每天的正常产出全报上来：
      · 路径里带「修正帧」目录    · 文件名里带「镜头<镜头号>」

    （2026-10-04：一直在用 04:11 的底稿，而 修正帧/ 里躺着 13:42 的候选，
      整整九个半小时没发现。**"现在最新的是哪一张"必须每次开工确认。**）
    """
    if not 底稿相对路径:
        return []
    底稿全 = os.path.join(根, 底稿相对路径)
    if not os.path.exists(底稿全):
        return []
    底稿时间 = os.path.getmtime(底稿全)
    命中 = []
    for 目录, 子目录们, 文件们 in os.walk(根):
        # 跳过备份与本工具的产出目录，它们天然比底稿新，报了是噪声
        子目录们[:] = [d for d in 子目录们 if d not in ("_旧版", "改图出图", ".git", "__pycache__")]
        for f in 文件们:
            if not f.lower().endswith((".png", ".jpg", ".jpeg")):
                continue
            全 = os.path.join(目录, f)
            if not os.path.exists(全) or os.path.samefile(全, 底稿全):
                continue
            if os.path.getmtime(全) <= 底稿时间:
                continue
            相对 = os.path.relpath(全, 根)
            if ("修正帧" in 相对) or (("镜头%s" % 镜头号) in f):
                命中.append((相对, os.path.getmtime(全)))
    命中.sort(key=lambda t: -t[1])
    return 命中


# 「--要改」里出现这些词 = 你在要求"拿掉某样东西"。每一条都必须有定稿依据。
否定词 = ["不许", "不得", "不要", "去掉", "删掉", "移除", "擦掉", "不能有", "不再有", "避免"]


def 查否定(镜, 要改):
    """「--要改」里每出一条否定，就把定稿核对项摆出来让人逐条对。

    **不拦路，只逼你看一眼定稿。** 判据出自定稿，不是自己编的 —— 这条最重要。
    """
    命中的词 = [w for w in 否定词 if w in (要改 or "")]
    if not 命中的词:
        return []
    核对项 = ((镜.get("定稿参考") or {}).get("核对项") or [])
    行 = ["「--要改」里有 %d 个否定措辞（%s）—— 逐条跟定稿核对项对一遍："
          % (len(命中的词), "、".join(命中的词))]
    if 核对项:
        for i, 项 in enumerate(核对项, 1):
            行.append("            □ %d. %s" % (i, 项))
    else:
        行.append("            （清单里「定稿参考.核对项」是空的，没得对 —— 先回去补）")
    行.append("          ↑ 定稿里**真的没有**你要求拿掉的那样东西吗？")
    行.append("            定稿里有 → **这条要求是错的，删掉它**（2026-10-04 就是这么错了一整天）。")
    return ["\n".join(行)]


def 校验(清单, 根, 镜头号, 要改):
    """返回 (问题列表, 元素列表)。问题非空 → 不许往下走。"""
    问题 = []
    if not (清单.get("全局风格") or "").strip():
        问题.append("清单缺少「全局风格」段。每一条改图提示词都必须带完整的全局风格块。")

    镜头表 = 清单.get("镜头") or {}
    if 镜头号 not in 镜头表:
        问题.append("清单里没有「镜头 %s」。改图前必须先把这一镜的元素填进清单。" % 镜头号)
        return 问题, [], [], {}

    镜 = 镜头表[镜头号]
    新建 = 是新建项目(清单)

    # —— 关卡 A：底稿 ——
    底稿 = 镜.get("底稿")
    if not 底稿:
        问题.append("「底稿」字段是空的。改图必须指明改的是哪一帧。")
    else:
        全 = os.path.join(根, 底稿)
        if not os.path.exists(全):
            问题.append("底稿文件不存在：%s" % 全)

    # —— 关卡 H（铁律六·取帧依据）：这个底稿，是不是这一镜「元素最全」的那一帧？ ——
    # 2026-10-05 的根因：镜头02 长 11 秒（6.0~17.0s），我截了 t=7.5 当底稿 ——
    #   那一格棋子还全在左上暂存区、板上光秃秃，而「道路和村庄摆在哪」**正是这一帧唯一
    #   该钉住的东西**，一个都没钉住。元素最全的是 t≈16.0。两个错叠在一起：
    #     ① 取帧范围只铺到 t=11.5，而落子发生在 12 秒之后 —— 正确的帧压根不在我扫的区间里；
    #     ② 挑选标准挑反了：按「暂存区干净、没红叉」挑，恰好挑走信息最少的那一格。
    # 修法：底稿默认 = 本镜「元素最全」的那一帧；不一样就必须在「例外理由」里说清楚，
    #       并把有病的帧写进「已知问题帧」。
    取帧 = 镜.get("取帧")
    if not isinstance(取帧, dict) or not 取帧:
        问题.append(
            "【拦住】没填「取帧」—— 这个底稿是怎么从整个镜头里挑出来的？\n"
            "          → 铁律六：**底稿默认取「这一镜里元素最全的那一帧」**。\n"
            "            起点不全，改出来的也不可能全。\n"
            "          → 跑 tools/取帧.py 扫满整个镜头区间，它会打印可直接粘进清单的模板。\n"
            "          → 2026-10-05 就是没做这一步：挑了张棋子还在暂存区、板上光秃秃的帧，\n"
            "            而这一帧唯一该钉住的道路和村庄位置，一个都没钉住。")
    else:
        区间 = 取帧.get("全镜头区间")
        命令 = str(取帧.get("取帧命令") or "")
        最全 = str(取帧.get("元素最全帧") or "").strip()
        底稿声明 = str(取帧.get("底稿") or "").strip()
        例外 = str(取帧.get("例外理由") or "").strip()
        已知 = 取帧.get("已知问题帧") or []

        if not (str(取帧.get("取帧依据") or "").strip()):
            问题.append(
                "【拦住】「取帧.取帧依据」是空的 —— 你凭什么说这一格元素最全？\n"
                "          → 一句话说清：这一格比别的格**多了什么**，所以它最全。\n"
                "          → 写不出来 = 你没逐格看过 = 拦下。")

        if (not isinstance(区间, list)) or len(区间) != 2:
            问题.append(
                "【拦住】「取帧.全镜头区间」必须是两个数 [起, 止]，写的是**这一镜从头到尾**的秒数。\n"
                "          → 不许只写你扫的那一段。2026-10-05 就是扫到 11.5s 收工，\n"
                "            而落子在 12.0s 之后，正确的帧根本不在扫过的范围里。")
        else:
            import re as _re
            起数 = _re.search(r"--起\s+([\d.]+)", 命令)
            止数 = _re.search(r"--止\s+([\d.]+)", 命令)
            if not 命令:
                问题.append("【拦住】「取帧.取帧命令」是空的 —— 把你实际跑的那条命令原样贴进来。")
            elif 新建 and not (起数 and 止数):
                # 新建项目：锚定帧是凭空做出来的，**没有成片可扫**，
                # 所以不要求 `--起/--止`。但必须换个说法交代清楚它凭什么长这样。
                来源 = str(取帧.get("锚定帧来源") or "").strip()
                if not 来源:
                    问题.append(
                        "【拦住】「项目类型」= 新建，但这张锚定帧**凭什么长这样**没写。\n"
                        "          → 新建项目没有成片可扫，所以不问「你扫满没有」，\n"
                        "            改问：这张帧**由什么生成**（哪张定款图 + 哪句提示词）？\n"
                        "          → 请填「取帧.锚定帧来源」。")
                else:
                    接缝 = 取帧.get("是否接缝帧") is True
                    if 接缝 and not str(取帧.get("接缝说明") or "").strip():
                        问题.append(
                            "【拦住】这张是**接缝帧**（同时是上一块的末帧和下一块的首帧），\n"
                            "          但没写「取帧.接缝说明」—— 下一块的首帧必须**指回同一张图**。\n"
                            "          → 接缝两侧锚在同一张图上，色差与位移才天然为零。")
            elif not (起数 and 止数):
                问题.append(
                    "【拦住】「取帧.取帧命令」里读不出 `--起` / `--止`，没法核对扫没扫满。\n"
                    "          → 若本项目**没有成片可扫**（帧是凭空做出来的），\n"
                    "            请在清单顶层写 `\"项目类型\": \"新建\"`，并填「取帧.锚定帧来源」。")
            else:
                扫起, 扫止 = float(起数.group(1)), float(止数.group(1))
                if abs(扫起 - 区间[0]) > 0.05 or abs(扫止 - 区间[1]) > 0.05:
                    问题.append(
                        "【拦住】取帧命令只扫了 %.1f~%.1fs，而这一镜是 %.1f~%.1fs —— **没铺满整个镜头**。\n"
                        "          → 元素最全的那一帧可能就落在你**没扫的那一段**里。回去扫满再来。"
                        % (扫起, 扫止, 区间[0], 区间[1]))

        if not 最全:
            问题.append("【拦住】「取帧.元素最全帧」是空的 —— 扫完之后，最全的是哪一格（写图路径）。")
        elif not os.path.exists(os.path.join(根, 最全)):
            问题.append("「取帧.元素最全帧」找不到文件：%s" % os.path.join(根, 最全))
        if not 底稿声明:
            问题.append("【拦住】「取帧.底稿」是空的 —— 实际拿去改的是哪一格？（应等于上面的「底稿」字段）")
        elif 底稿 and 底稿声明 != 底稿:
            问题.append(
                "【拦住】「取帧.底稿」(%s) 跟清单「底稿」(%s) 不是同一张。\n"
                "          → 两处必须写同一张图，否则关卡查的和你改的不是同一件事。" % (底稿声明, 底稿))

        # 核心判定：底稿 = 元素最全帧；例外必须留痕
        if 最全 and 底稿 and os.path.basename(底稿) not in 最全 and 最全 not in 底稿:
            if not 例外:
                问题.append(
                    "【拦住】底稿不是这一镜「元素最全」的那一帧，而且没说为什么。\n"
                    "          → 铁律六：**默认取最全的那一格**。起点不全，改出来的也不可能全。\n"
                    "          → 若你**明确知道**这一格有病、必须先拿它改，就在「例外理由」里写清楚，\n"
                    "            并把有病的帧写进「已知问题帧」。\n"
                    "          → 元素最全帧：%s\n            实际底稿：%s" % (最全, 底稿))
            elif not 已知:
                问题.append(
                    "【拦住】填了「例外理由」却没列「已知问题帧」—— 例外只允许一种原因：\n"
                    "          **你知道某一帧有病、必须先修它**。那就把那一帧写进「已知问题帧」。\n"
                    "          → 「懒得扫」「随手截的」不是例外理由。")

        # 新建项目不适用「例外」这个概念：它没有成片可扫，也就无所谓「没扫满」，
        # 更没有「某一帧有病、必须先拿它改」这种例外。所以这条成对校验对新建项目跳过。
        if 例外 and not 已知 and not 新建:
            问题.append("【拦住】有「例外理由」但「已知问题帧」是空的 —— 两者必须成对出现。")

    # —— 关卡 E（铁律四·来源核对）：写「不许/必须」之前，先打开定稿看一眼 ——
    # 2026-10-04 的根因：提示词里写了「不许有奶油白底板」，而定稿地图（03-总地图_v15）
    # **本身就是带奶油白底板的**。那条要求是从上一轮的救火脚本里抄来的，没人回去核对源头。
    # 一条错要求 → 白烧 18 积分，还带歪了后面所有判断。
    定稿参考 = 镜.get("定稿参考") or {}
    if not (定稿参考.get("图") or "").strip():
        问题.append(
            "【拦住】没填「定稿参考.图」—— 这一镜最终的定稿参考图到底是哪一张？\n"
            "          → 铁律四：写任何「不许 X / 去掉 X / 必须 Y」之前，先把定稿打开看一眼。\n"
            "          → 出处必须是**定稿参考图**，不能是「上一轮的提示词 / 救火脚本 / 上一版清单」。")
    elif not os.path.exists(os.path.join(根, 定稿参考["图"])):
        问题.append("「定稿参考.图」找不到文件：%s" % os.path.join(根, 定稿参考["图"]))

    if not (定稿参考.get("长这样") or "").strip():
        问题.append(
            "【拦住】没填「定稿参考.长这样」—— 用一句话说出定稿图上跟本版有关的地方长什么样。\n"
            "          → **写不出来 = 你没看过它。** 这一步不做，后面全是在猜。\n"
            "          → 例：定稿版图的 10 号地块是两只羊；版图带一圈奶油白底板。")

    核对项 = 定稿参考.get("核对项") or []
    if not 核对项:
        问题.append(
            "【拦住】「定稿参考.核对项」是空的 —— 出图之后，你拿什么逐项对？\n"
            "          → 逐条写**一眼能看真假**的项：数量、有无、颜色、位置。\n"
            "          → 反面例子：「版图正确」（没法判）。正面例子：「10 号地块两只羊」。")

    # —— 关卡 F：底稿新鲜度 —— 防止拿一张过期的底稿一路改下去 ——
    更新 = 找更新的候选(根, 底稿, 镜头号)
    if 更新 and not (镜.get("已确认最新底稿") or "").strip():
        最近 = "\n".join("            · %s   %s" % (p, time.strftime("%m-%d %H:%M", time.localtime(t)))
                        for p, t in 更新[:5])
        问题.append(
            "【拦住】有 %d 张比底稿更新、且像是本镜候选的图 —— 底稿确定是最新的吗？\n"
            "%s\n"
            "          → 确认过了（说清楚为什么仍用这张）就填「已确认最新底稿」。\n"
            "          → 没确认过 = 拦下。2026-10-04 就是拿 04:11 的旧底稿跑了一整天，\n"
            "            而 修正帧/ 里躺着 13:42 的候选，**九个半小时没发现有更新的**。"
            % (len(更新), 最近))

    # —— 关卡 G（铁律五·截帧即定清单）：这个 bug 帧到底病在哪几条？ ——
    # 2026-10-04 的四次返工根因：**把某一帧定为底稿的那一刻，没把它的病列清楚**。
    # 只零碎记了「底板要不要留」「羊够不够大」，没成清单。于是改到一半，
    # 连「版图上该有几条路」这种**三份定稿里明明写着**的事，都要回头问用户。
    # 修法：底稿 = bug 帧 → **当场**逐条列出问题（问题/现况/应为/出处），
    # 之后每一版改图都是围绕这份清单销项；**清单没销完、或冒出清单外的新问题，都不许定稿**。
    帧清 = 镜.get("帧问题清单") or {}
    条目 = 帧清.get("问题") or []
    if not 条目:
        # 铁律五本意是「把某帧定为 **bug 帧** 的那一刻，当场把病列清楚」。
        # 新建项目的锚定帧（定款帧 / 接缝帧）**不是 bug 帧**，无病可列 —— 允许为空。
        # 只有明确标了「本帧是bug帧=true」的才强制要求填清单。
        if not (新建 and 镜.get("本帧是bug帧") is not True):
            问题.append(
                "【拦住】没填「帧问题清单.问题」—— 这个底稿是 bug 帧，它病在哪几条？\n"
                "          → 铁律五：**把某一帧定为底稿的那一刻**，就要把它的病逐条列清楚；\n"
                "            不是改到一半再回头问用户「这里到底该是什么样」。\n"
                "          → 每条写四件套：问题 / 现况 / 应为 / 出处，另外记「状态」。\n"
                "          → 若这是新建项目的锚定帧、本来就不是 bug 帧：\n"
                "            在清单顶层写 `\"项目类型\": \"新建\"`，或给本镜标 `\"本帧是bug帧\": false`。")
    else:
        for j, 条 in enumerate(条目, 1):
            号 = 条.get("号", j)
            缺 = [f for f in ("问题", "现况", "应为", "出处")
                  if not str(条.get(f) or "").strip()]
            if 缺:
                问题.append(
                    "【拦住】帧问题清单 第 %s 条缺「%s」—— 四件套缺一不可。\n"
                    "          → 「出处」只认**定稿**（定稿图 / 定稿文档 / 定稿脚本）。\n"
                    "            写「我的印象 / 上一轮的提示词 / 上一版清单」= 没有出处。" % (号, "、".join(缺)))
            if not str(条.get("状态") or "").strip():
                问题.append("【拦住】帧问题清单 第 %s 条没填「状态」（未销 / 已销）。" % 号)

    # —— 关卡 A：元素清单 ——
    # 字段名兼容：老项目（案例）写 `画面元素`，新项目写 `元素`。
    # —— 2026-10-07：手册正文只写「元素」、速查表写「画面元素」，两边漂了，
    #    照正文写就会被无条件拦下。这里两种都认，并把权威名统一为 `画面元素`。
    元素 = 镜.get("画面元素") or 镜.get("元素") or []
    if not 元素:
        问题.append("「画面元素」是空的。改图前必须先把这张画面里有哪些元素逐条列出来。"
                    "（字段名写 `画面元素` 或 `元素` 均可）")

    for i, e in enumerate(元素, 1):
        名 = (e.get("名") or "").strip()
        if not 名:
            问题.append("第 %d 个元素没有「名」。" % i)
            continue
        if not (e.get("管") or "").strip():
            问题.append("元素「%s」没写「管」—— 每张参考图必须点名它只管哪一维。" % 名)
        if not (e.get("本版") or "").strip():
            问题.append("元素「%s」没填「本版」—— 是「照抄」还是「换」？漏填 = 没想清楚。" % 名)
            continue

        # —— 关卡 C（铁律三第一步）：逐条判断"这一版碰不碰它" ——
        # 这个字段是"改 bug 提示词必须重写"的落地：不碰的 = 不挂图、不写进提示词。
        # 漏填 = 没判断过 = 拦下。
        if "本版碰它" not in e:
            问题.append(
                "【拦住】元素「%s」没填「本版碰它」—— 这一版到底碰不碰它？\n"
                "          → 必须逐个元素判断（铁律三·第一步）：不碰的，参考图不挂、提示词里一个字都不写。\n"
                "          → 漏填 = 没做这一步判断 = 拦下。" % 名)
            continue

        碰 = e["本版碰它"] is True

        # —— 关卡 B：要换的东西，必须给图 ——
        # 新建项目例外：锚定帧**本身就是要产出的定稿**，它里面的元素
        # （定款帧的产线、工位……）是这一帧第一次出现，**没有上游定稿图可挂** ——
        # 要求它给图就是循环依赖（图还没生成，拿什么当定稿？）。
        # 这时把关交给「取帧.锚定帧来源」（说清怎么生成）+「定稿参考.核对项」（生成后逐项对），
        # 而不是交给一张不存在的图。
        图 = (e.get("定稿图") or "").strip()
        if 碰 and e["本版"] != 照抄 and not 图 and not 新建:
            问题.append(
                "【拦住】元素「%s」本版=%s，却没给「定稿图」。\n"
                "          → 你要动它，就必须把它的定稿图挂上来；给不出说明还没定稿。\n"
                "          → 2026-09-30 就是死在这一条：要换地图，却没挂新地图。\n"
                "          → 若这是**新建项目的锚定帧**（元素本就是本帧第一次出现）:\n"
                "            在清单顶层写 `\"项目类型\": \"新建\"`，并把「取帧.锚定帧来源」写清楚。"
                % (名, e["本版"]))
        if 图 and not os.path.exists(os.path.join(根, 图)):
            问题.append("元素「%s」的定稿图找不到：%s" % (名, os.path.join(根, 图)))

    挂图数 = len(挂图列表(元素)) if 底稿 else 0
    if 挂图数 > 最多挂图:
        问题.append("要挂 %d 张图，超过 CLI 上限 %d 张，要先精简。" % (挂图数, 最多挂图))

    # —— 提示（不拦路）：清单和「--要改」有没有互相打架 ——
    警告 = []
    for e in 元素:
        名 = (e.get("名") or "").strip()
        if not 名:
            continue
        提到 = any(w in 要改 for w in 提过的词(名))
        if e.get("本版碰它") is not True:
            if 提到:
                警告.append(
                    "「--要改」里提到了「%s」，但清单标了「本版碰它=false」——\n"
                    "          不碰的东西不该出现在提示词里（铁律三）。到底动不动？" % 名)
            continue
        if e.get("本版") != 照抄 and not 提到:
            警告.append("清单把「%s」标成要动，但「--要改」里没提到它 —— 确认一下是不是漏写了。" % 名)

    return 问题, 警告, 元素, 镜


def 挂图列表(元素):
    """挂到即梦上的图，顺序 = --images 的顺序，第 1 张永远是底稿。

    🔴 组提示词 与 提交 都**只能**从这个函数取图，保证「图 N」的编号和实际上传
    顺序不可能对不上。（草稿版就是栽在这：编号按元素序号走，跳过没有定稿图的元素时
    空号照涨 —— 提示词说「图 3 是新地图」，实际上传的第 3 张是别的东西。
    这种错**静默、致命、还查不出来**。）

    🔴 铁律三：**只挂「这一版会碰到」的元素**（清单里 `本版碰它` = true）。
    不变的元素的参考图不挂 —— 挂上去 = 喊模型重画它。
    """
    挂 = [{"名": "底图（原始待修帧）", "管": "构图、机位、透视", "本版": 照抄, "_底稿": True}]
    for e in 元素:
        if e.get("本版碰它") is True and (e.get("定稿图") or "").strip():
            挂.append(e)
    return 挂


def 提过的词(名):
    """把元素名拆成几个候选词，用来粗筛「--要改」里有没有提到它。
    中文同义（总地图 / 版图）最终靠人判断，这里**宁松勿紧** —— 误报多了就没人看了。"""
    import re
    词 = set()
    for p in re.split(r"[（）()、/／与和]", 名 or ""):
        p = p.strip()
        if p:
            词.add(p)
            词.add(re.sub(r"^(整片|整块|整个)", "", p))
    return {w for w in 词 if w}


# 「重述已有内容」高风险词。出现在不该出现的位置，就是在喊模型重画那块。
# **宁松勿紧** —— 误报多了就没人看了。
重述词 = ["背景", "桌面", "木纹", "渐变", "明暗", "压暗", "暗角", "姿态", "位置", "大小"]


def 取风格(清单):
    """改图提示词里该用的风格段。返回 (风格文本, 警告列表)。

    铁律三：改图**只留跟这一版要改的那一块相关**的风格，**不许整段照抄**从零生成用的
    `全局风格`。所以清单里优先用 `全局风格_改图` —— 那是剥掉了"影响改图"的句子之后的版本
    （背景色值、构图/留白、压暗类措辞）。

    没给 `全局风格_改图` 就退回 `全局风格` 并告警 —— 那多半意味着这一步还没做。
    """
    改图风格 = (清单.get("全局风格_改图") or "").strip()
    if 改图风格:
        return 改图风格, []
    return (清单.get("全局风格") or "").strip(), [
        "清单没给「全局风格_改图」，只能整段照抄「全局风格」——改图应只留相关风格（铁律三）。\n"
        "          建议剥掉这几类：背景色值、构图/留白、压暗类措辞。"]


def 查重述(清单, 镜, 色值):
    """扫出「正在描述原图已有的东西」的地方 —— 那就是漂移的推手。

    依据（2026-09-30 用户定规 + 实测）：
      血统链 v1→v9 背景区 R 159.5→151.7、G 111.0→102.5，**单调往下**（抖动基线仅 3）。
      方向一致 = 提示词里有东西在推，不是噪声。
    """
    警告 = []

    命中 = [w for w in 重述词 if w in (色值 or "")]
    if 命中:
        警告.append(
            "「本镜色值」里出现了「%s」—— 这些多半是**原图已经有**的东西。\n"
            "          给它写色值 = 喊模型重画它。只留这一版新画那一块要用的色，其余删掉。"
            % "」「".join(命中))

    # 「不许变」不在这里查 —— 新模板结构上已经不会把它写进提示词（见 组提示词 docstring）。
    # 它仍留在清单里当人工备忘，但那是个**不流进提示词**的字段，查它属于空响。

    # 只查**真会流进提示词**的那份风格（优先 全局风格_改图）。
    风格, 风格警告 = 取风格(清单)
    警告 += 风格警告
    风格命中 = [w for w in ("压暗", "暗角", "加深", "变暗") if w in 风格]
    if 风格命中:
        警告.append(
            "这份风格里还有「%s」—— 往暗里推的措辞**每版都重喂一次**，是背景逐版变暗的嫌疑源。\n"
            "          确认一下它是不是「描述已画好的东西」；是的话剥掉。"
            % "」「".join(风格命中))
    return 警告


def 组提示词(清单, 元素, 镜, 要改):
    """按 skill 8.4 的分工表模板拼提示词。图号取自 挂图列表()，严格对应 --images 的顺序。

    🔴 2026-09-30 用户定规（铁律三）：**改 bug 的提示词必须重写，不许复用原提示词。**

    这是**两个方向相反的任务**：
      · **从零生成**：把画面里每样东西都描述一遍 —— 对的。
      · **改 bug**：重点是"改掉有 bug 的那一块，其余保持原图"。
        此时再描述一遍已画好的东西，就是**多余的绘制指令** —— 模型会把它们重画。
        原提示词里**有用的部分可以用，没用的部分必须删掉**，结合它写一版新的。

    实测血统链 v1→v9（同一提示词反复重喂）：背景区 R 159.5→151.7、G 111.0→102.5，
    **一路单调往下**（抖动基线只有 3）—— 方向一致 = 是提示词在推，不是噪声。

    所以本模板只写四样：
      ① 风格（只写跟这一版要改的那块相关的）+ 一句"与图 1 完全一致、不许整体加深"
      ② 这一版**唯一**要改的那一处（说清"变成什么样"）
      ③ 「其余一个像素都别动」—— **指着原图说，不是把原图描述一遍**
      ④ 参考图分工表，**只列「这一版会碰到」的元素**（见 挂图列表）
    **「不许变」的逐条枚举不再进提示词**；「本镜色值」只留**这一版新画的那一块**要用的色。
    """
    挂 = 挂图列表(元素)
    行 = []
    行.append("【风格】整幅画必须与图 1 **完全同一画风、同一光照方向、同一明暗、同一配色体系** —— "
             "图 1 什么样就保持什么样。")
    行.append("**不许整体加深、不许加强暗角、不许把任何已有区域重画或微调。**")
    行.append(取风格(清单)[0])
    行.append("")

    色值 = (镜.get("本镜色值") or "").strip()
    if 色值:
        行.append("【本版新画的那一块要用的色值】%s" % 色值)
        行.append("")

    行.append("【任务】这是一段 MG 动画里的一帧画面（竖版 9:16）。")
    行.append("输入的第 1 张图是本帧的底图。本帧只做下面这一件事。")
    行.append("")

    行.append("【参考图清单 —— 每张图只负责一件事】")
    for i, e in enumerate(挂, 1):
        if e.get("_底稿"):
            行.append("- 图 %d「底图（原始待修帧）」：**只负责构图、机位、透视**，"
                       "以及下面没点名要改的部分一律照抄它。" % i)
        elif e["本版"] == 照抄:
            行.append("- 图 %d「%s」：**只负责「%s」**。它只作锚 —— 画面里它所在的位置与大小一律照图 1，不许动。"
                       % (i, e["名"], e["管"]))
        else:
            行.append("- 图 %d「%s」：**只负责「%s」**。**本版以它为准重画**，与图 1 不一致的地方一切以它为准。"
                       % (i, e["名"], e["管"]))
    行.append("")

    行.append("【这一版唯一的改动】%s" % 要改.strip())
    行.append("")
    行.append("【其余一律不动】除上面点名的那一处，画面其余部分**一个像素都不要动** —— "
             "直接沿用图 1 的像素。不要重画、不要重新描述、不要微调、不要整体加深或压暗。")
    行.append("")

    文字 = (镜.get("画面内文字") or "").strip()
    if 文字:
        行.append("【画面内文字】%s" % 文字)
    禁止 = (镜.get("禁止") or "").strip()
    if 禁止:
        行.append("【禁止】%s" % 禁止)

    return "\n".join(行)


def 提交一张(图列表, 提示词, 比例, 分辨率, 模型, 输出路径, 日志):
    """提交一次、解析 JSON、下载出图。返回 (状态, 积分, 路径或 None)。"""
    命令 = ["dreamina", "image2image",
            "--images", ",".join(图列表),
            "--prompt=" + 提示词,
            "--ratio=" + 比例,
            "--resolution_type=" + 分辨率,
            "--model_version=" + 模型]
    结果 = subprocess.run(命令, capture_output=True, text=True)
    原文 = (结果.stdout or "") + (结果.stderr or "")
    日志.write("\n===== %s =====\n%s\n" % (os.path.basename(输出路径), 原文))

    if not 原文.strip():
        # 零输出 + 秒退 = 参数没解析进去（skill 9.3），不是网络问题，别重试
        return "零输出(参数没解析进去)", 0, None

    i = 原文.find("{")
    if i < 0:
        return "没有 JSON", 0, None
    try:
        d = json.loads(原文[i:])
    except Exception as exc:
        return "JSON 解析失败:%s" % exc, 0, None

    st = d.get("gen_status", "?")
    cc = d.get("credit_count", 0) or 0
    图s = (d.get("result_json") or {}).get("images") or []
    url = 图s[0].get("image_url", "") if 图s else ""
    if st != "success" or not url:
        return st, cc, None

    subprocess.run(["curl", "-sL", "--max-time", "180", "-o", 输出路径, url], check=False)
    好了 = os.path.exists(输出路径) and os.path.getsize(输出路径) > 0
    return st, cc, (输出路径 if 好了 else None)


